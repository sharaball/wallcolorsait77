const KEY = "wall-start-time";
const UNLOCK_SECONDS = 5;

const stage = document.getElementById("stage");
const alarmAudio = new Audio("uploads/signalizachiya.mp3");
alarmAudio.loop = true;

let scores = { ...RESET_SCORES };
let step = 0;
let offlineElapsed = 0;
let bonusClaimed = false;
let bonusUsed = false;
let alarmActive = false;

const BONUS_KEY = "wall-bonus-claimed";

function bonusClaimedOnce() {
  try { return localStorage.getItem(BONUS_KEY) === "1"; } catch { return bonusClaimed; }
}

function unlockedCount(total) {
  if (total <= 0) return 0;
  const byTime = Math.floor(offlineElapsed / UNLOCK_SECONDS);
  const bonus = bonusClaimedOnce() && !bonusUsed ? 5 : 0;
  return Math.min(total, byTime + bonus);
}

function shuffle(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

function colorForDefault(index) {
  return PALETTE[index % PALETTE.length];
}

function optionList(q) {
  if (q.type === "choice") {
    const textOpts = shuffle(q.options.slice());
    return textOpts.map((text, i) => ({ text, color: colorForDefault(i) }));
  }
  return q.options;
}

function render() {
  const q = QUESTIONS[step];
  const options = optionList(q);
  const isChoice = q.type === "choice";
  const pct = Math.round((step / QUESTIONS.length) * 100);

  stage.innerHTML = `
    <div class="card">
      <h1 class="title">Цвет стены</h1>
      <p class="subtitle">Абсурдные вопросы про голландцев — узнай, какая ты стена.</p>
      <div class="progress"><div class="progress__bar" style="width:${pct}%"></div></div>
      <h2 class="question">${q.q}</h2>
      ${
        isChoice
          ? `<div class="meter"><div class="meter__label" id="meterLabel"></div><div class="meter__track"><div class="meter__fill" id="meterFill"></div></div></div>`
          : ""
      }
      <div class="options" id="opts">
        ${options
          .map((o, i) => `<button class="option locked" data-i="${i}">${o.text}</button>`)
          .join("")}
      </div>
    </div>`;

  stage.querySelectorAll(".option").forEach((btn) => {
    btn.addEventListener("click", () => {
      const opt = options[btn.dataset.i];
      if (btn.classList.contains("locked")) return;
      if (q.type === "truefalse") {
        if (opt.color === "beige") {
          scores = { ...RESET_SCORES };
          step = 0;
          render();
        } else {
          scores[opt.color]++;
          advance();
        }
        return;
      }

      if (isChoice) {
        scores[opt.color]++;
        advance();
      }
    });
  });

  updateMeter();
}

function unlockLimit(total) {
  return unlockedCount(total);
}

function updateMeter() {
  const q = QUESTIONS[step];
  if (!q) return;
  const total = q.options.length;
  const unlocked = unlockLimit(total);
  const hasMeter = document.getElementById("meterLabel") && document.getElementById("meterFill");
  if (hasMeter) {
    const label = document.getElementById("meterLabel");
    const fill = document.getElementById("meterFill");
    label.textContent = `Доступно ответов: ${unlocked} из ${total}`;
    fill.style.width = `${(unlocked / total) * 100}%`;
  }

  const btns = stage.querySelectorAll(".option");
  btns.forEach((btn) => {
    const i = Number(btn.dataset.i);
    if (i < unlocked) btn.classList.remove("locked");
    else btn.classList.add("locked");
  });
}

function advance() {
  step++;
  if (step < QUESTIONS.length) render();
  else showResult();
}

function showResult() {
  const winner = Object.keys(scores).reduce((a, b) => (scores[a] >= scores[b] ? a : b));
  const r = RESULTS[winner];
  stage.innerHTML = `
    <div class="card result">
      <div class="result__swatch" style="background:${r.color}"></div>
      <div class="result__name">${r.name}</div>
      <p class="result__text">${r.text}</p>
      <button class="restart">Пройти ещё раз</button>
    </div>`;
  stage.querySelector(".restart").addEventListener("click", () => {
    scores = { ...RESET_SCORES };
    step = 0;
    render();
  });
}

setInterval(() => {
  if (!navigator.onLine) offlineElapsed += 0.5;
  if (QUESTIONS[step] && !stage.querySelector(".result")) {
    updateMeter();
  }
}, 500);

function showAlarm() {
  const already = bonusClaimedOnce();
  if (alarmActive) return;
  alarmActive = true;
  alarmAudio.currentTime = 0;
  alarmAudio.play().catch(() => {});
  const body = already
    ? `<p class="alarm-text">
        Вы ушли со страницы! Никуда не уходите!<br>
        Новые ответы получаются оффлайн.
      </p>
      <button class="alarm-claim" id="alarmClaim">Вернуться</button>`
    : `<p class="alarm-text">
        Новые ответы получаются оффлайн — и не выходите сейчас!<br>
        Вы ушли со страницы! Никуда не уходите!<br>
        Заберите приз — он уже тут.
      </p>
      <button class="alarm-claim" id="alarmClaim">Забрать +5 ответов сейчас</button>`;
  stage.insertAdjacentHTML(
    "beforeend",
    `<div class="alarm-overlay" id="alarmOverlay">
      <div class="alarm-box">
        <div class="alarm-title"><span class="pulse">ВНИМАНИЕ!</span></div>
        ${body}
      </div>
    </div>`
  );
  document.getElementById("alarmClaim").addEventListener("click", () => {
    if (!already) {
      try { localStorage.setItem(BONUS_KEY, "1"); } catch {}
      bonusClaimed = true;
      bonusUsed = true;
    }
    const ov = document.getElementById("alarmOverlay");
    if (ov) ov.remove();
    alarmAudio.pause();
    alarmAudio.currentTime = 0;
    alarmActive = false;
    if (QUESTIONS[step] && !stage.querySelector(".result")) updateMeter();
  });
}

let armed = false;
setTimeout(() => { armed = true; }, 800);

function watchLeaving() {
  document.addEventListener("visibilitychange", () => {
    if (armed && document.hidden) showAlarm();
  });
  window.addEventListener("blur", () => {
    setTimeout(() => {
      if (armed && (!document.hasFocus() || document.hidden)) showAlarm();
    }, 200);
  });
}

watchLeaving();
render();
